-- Revenue Engine customer quote/checkout table.
-- Apply only to the Production database after the matching application code is reviewed.
-- Additive only; no existing leads, requests, payments, or webhooks are rewritten.
BEGIN;

CREATE TABLE IF NOT EXISTS public.client_orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id TEXT NOT NULL UNIQUE,
    client_request_id INTEGER NOT NULL REFERENCES public.client_requests(id),
    token_hash TEXT NOT NULL UNIQUE,
    amount INTEGER NOT NULL CHECK (amount > 0),
    currency TEXT NOT NULL DEFAULT 'INR',
    scope_summary TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'QUOTE_PREPARED',
    razorpay_order_id TEXT UNIQUE,
    razorpay_payment_id TEXT UNIQUE,
    expires_at TEXT NOT NULL,
    quote_sent_at TEXT,
    paid_at TEXT,
    error_note TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE INDEX IF NOT EXISTS idx_client_orders_request
    ON public.client_orders(client_request_id, id);
CREATE INDEX IF NOT EXISTS idx_client_orders_status
    ON public.client_orders(status, expires_at);

COMMIT;
