-- Revenue Engine Phase 1 production schema additions.
-- Run only after the read-only duplicate-email preflight returns zero duplicate groups.
-- Apply this file from the Production database SQL console as the database owner.
-- This script does not modify existing lead, outreach, payment, or client-request rows.

BEGIN;

ALTER TABLE public.consultation_submissions
    ADD COLUMN IF NOT EXISTS lead_id INTEGER REFERENCES public.leads(id);

CREATE TABLE IF NOT EXISTS public.follow_up_schedule (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id INTEGER NOT NULL REFERENCES public.leads(id),
    source_outreach_id INTEGER NOT NULL REFERENCES public.outreach(id),
    attempt_number INTEGER NOT NULL,
    due_at TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'SCHEDULED',
    claimed_at TEXT,
    prepared_outreach_id INTEGER REFERENCES public.outreach(id),
    cancellation_reason TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
    updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
    UNIQUE (lead_id, attempt_number)
);

ALTER TABLE public.follow_up_schedule
    ADD COLUMN IF NOT EXISTS claimed_at TEXT;

CREATE TABLE IF NOT EXISTS public.consultation_handoff_tokens (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash TEXT NOT NULL UNIQUE,
    lead_id INTEGER NOT NULL REFERENCES public.leads(id),
    expires_at TEXT NOT NULL,
    used_at TEXT,
    consultation_public_id TEXT,
    created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE INDEX IF NOT EXISTS idx_follow_up_due
    ON public.follow_up_schedule(status, due_at);

CREATE INDEX IF NOT EXISTS idx_follow_up_lead
    ON public.follow_up_schedule(lead_id, attempt_number);

CREATE INDEX IF NOT EXISTS idx_handoff_lead
    ON public.consultation_handoff_tokens(lead_id, expires_at);

CREATE UNIQUE INDEX IF NOT EXISTS idx_leads_email_unique_normalized
    ON public.leads(LOWER(TRIM(email)))
    WHERE email IS NOT NULL AND TRIM(email) <> '';

COMMIT;
