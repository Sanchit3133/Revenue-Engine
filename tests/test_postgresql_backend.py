import os
import unittest
from unittest.mock import patch

from app import database


class TestDatabaseBackendSelection(unittest.TestCase):
    def test_production_never_falls_back_to_sqlite(self):
        production_settings = type(
            "ProductionSettings",
            (),
            {
                "environment": "production",
                "database_backend": "auto",
                "database_url": None,
            },
        )()
        with patch.object(database, "settings", production_settings):
            with self.assertRaisesRegex(database.DatabaseConfigurationError, "DATABASE_URL"):
                database.get_database_backend()

    def test_development_uses_sqlite_when_url_is_absent(self):
        development_settings = type(
            "DevelopmentSettings",
            (),
            {
                "environment": "development",
                "database_backend": "auto",
                "database_url": None,
            },
        )()
        with patch.object(database, "settings", development_settings):
            self.assertEqual(database.get_database_backend(), "sqlite")


@unittest.skipUnless(os.environ.get("DATABASE_URL"), "DATABASE_URL is not configured")
@unittest.skipIf(
    os.environ.get("REPL_DEPLOYMENT") == "1"
    or os.environ.get("ENVIRONMENT", "").lower() == "production",
    "Schema migrations are applied to production through Replit Publish.",
)
class TestPostgreSQLConnection(unittest.TestCase):
    def test_configured_postgres_executes_sql_and_returns_hybrid_rows(self):
        self.assertEqual(database.get_database_backend(), "postgresql")
        conn = database.connect()
        try:
            conn.execute(
                "CREATE TEMP TABLE backend_probe "
                "(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value TEXT UNIQUE)"
            )
            inserted = conn.execute(
                "INSERT INTO backend_probe(value) VALUES (?) RETURNING id, value",
                ("one",),
            ).fetchone()
            self.assertEqual(inserted[0], inserted["id"])
            self.assertEqual(tuple(inserted), (inserted["id"], "one"))

            ignored = conn.execute(
                "INSERT OR IGNORE INTO backend_probe(value) VALUES (?)",
                ("one",),
            )
            self.assertEqual(ignored.rowcount, 0)

            quoted = conn.execute(
                "SELECT ? AS number, 'literal ?' AS text",
                (17,),
            ).fetchone()
            self.assertEqual(quoted["number"], 17)
            self.assertEqual(quoted["text"], "literal ?")
        finally:
            conn.rollback()
            conn.close()

    def test_health_check_reports_postgresql(self):
        self.assertEqual(database.health_check(), "postgresql")

    def test_development_schema_upgrade_is_repeatable_and_preserves_rows(self):
        with database.connect() as conn:
            before = conn.execute("SELECT COUNT(*) FROM leads").fetchone()[0]
        database.init_db()
        database.init_db()
        with database.connect() as conn:
            after = conn.execute("SELECT COUNT(*) FROM leads").fetchone()[0]
            version_count = conn.execute(
                "SELECT COUNT(*) FROM schema_migrations WHERE version = ?",
                (1,),
            ).fetchone()[0]
        self.assertEqual(after, before)
        self.assertEqual(version_count, 1)


if __name__ == "__main__":
    unittest.main()
